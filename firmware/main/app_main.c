void trigger_alert(InferenceResult* result) {
    if (result->class_idx == 1 && result->confidence > 0.6f) {
        // Simulated alert: print to UART + would control vibration motor
        printf("ALERT: Anomaly detected! Confidence: %.1f%%\n", result->confidence * 100);
        // TODO: Set GPIO for vibration/buzzer
    }
}

