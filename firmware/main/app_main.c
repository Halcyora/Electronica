static float ecg_buffer[FEATURE_WINDOW_SIZE];
static int ecg_buffer_pos = 0;

void app_main(void) {
    printf("FractalPulse v1.0 - Starting...\n");
    
    // Initialize NVS (non-volatile storage)
    esp_err_t ret = nvs_flash_init();
    if (ret == ESP_ERR_NVS_NO_FREE_PAGES || ret == ESP_ERR_NVS_NEW_VERSION_FOUND) {
        ESP_ERROR_CHECK(nvs_flash_erase());
        ret = nvs_flash_init();
    }
    
    printf("Model loaded: %zu bytes\n", g_fractal_pulse_model_data_len);
    
    // Main monitoring loop
    while (1) {
        // TODO: Read ADC from ECG sensor
        // For now, simulate with synthetic data
        ecg_buffer[ecg_buffer_pos++] = sinf(2 * 3.14159f * ecg_buffer_pos / 250.0f);
        
        // When buffer is full, run feature extraction + inference
        if (ecg_buffer_pos >= FEATURE_WINDOW_SIZE) {
            printf("Running inference on %d samples...\n", ecg_buffer_pos);
            
            ECGFeatures features = extract_ecg_features(ecg_buffer, FEATURE_WINDOW_SIZE);
            InferenceResult result = run_inference(&features);
            
            printf("HR: %.1f bpm, HRV_SDNN: %.1f ms\n", features.hr, features.hrv_sdnn);
            printf("Inference: %s (confidence: %.1f%%)\n", 
                   result.class_idx == 0 ? "Normal" : "Anomaly", 
                   result.confidence * 100);
            
            trigger_alert(&result);
            
            // Reset buffer
            ecg_buffer_pos = 0;
        }
        
        vTaskDelay(1);  // 1ms task delay
    }
}
